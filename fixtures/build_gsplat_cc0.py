# ---------------------------------------------------------------------------
# the synthetic splat: a colour sphere shell on a Fibonacci lattice
# ---------------------------------------------------------------------------

def synthesize_ply(path):
    """Write a standard INRIA-convention 3D-Gaussian-Splatting PLY of a colour
    sphere shell. Pure function of the module constants; deterministic."""
    n = N_GAUSSIANS
    i = np.arange(n, dtype=np.float64)
    golden = math.pi * (3.0 - math.sqrt(5.0))          # the golden angle
    y = 1.0 - 2.0 * (i + 0.5) / n                       # y in (-1, 1)
    r = np.sqrt(np.clip(1.0 - y * y, 0.0, 1.0))
    theta = golden * i
    ux, uy, uz = r * np.cos(theta), y, r * np.sin(theta)   # unit directions
    unit = np.stack([ux, uy, uz], 1)

    means = (unit * RADIUS_M).astype(np.float64)

    # colour each Gaussian by its outward direction: a smooth r/g/b globe.
    rgb_lin = np.clip(0.5 + 0.5 * unit, 0.0, 1.0)          # in [0,1]
    f_dc = (rgb_lin - 0.5) / SH_C0                          # inverse of the DC eval

    # store spaces: scale is log, opacity is logit (the INRIA convention).
    log_scale = math.log(SCALE_M)
    logit_opacity = math.log(ALPHA / (1.0 - ALPHA))

    zeros = np.zeros(n, dtype=np.float64)
    ones = np.ones(n, dtype=np.float64)
    columns = [
        ("x", means[:, 0]), ("y", means[:, 1]), ("z", means[:, 2]),
        ("nx", zeros), ("ny", zeros), ("nz", zeros),      # INRIA writes zeros
        ("f_dc_0", f_dc[:, 0]), ("f_dc_1", f_dc[:, 1]), ("f_dc_2", f_dc[:, 2]),
        ("opacity", ones * logit_opacity),
        ("scale_0", ones * log_scale), ("scale_1", ones * log_scale),
        ("scale_2", ones * log_scale),
        ("rot_0", ones), ("rot_1", zeros), ("rot_2", zeros), ("rot_3", zeros),
    ]
    write_ply_binary(path, n, columns,
                     comments=["synthetic CC0 colour sphere shell, "
                               "fixtures/build_gsplat_cc0.py"])
    return path


def palette_from_dc(rgb_lin, bins=4, top=8):
    """A measured palette: a 4x4x4 histogram of the DC-band linear colours, top
    `top` bins by population, each swatch the MEAN linear colour of its bin — the
    same shape of computation embedding.layout.txt section 4 step 9 defines, and
    the same one build_gsplat_fixture.py uses, so the two spellings agree."""
    idx = np.clip((rgb_lin * bins).astype(np.int64), 0, bins - 1)
    key = (idx[:, 0] * bins + idx[:, 1]) * bins + idx[:, 2]
    counts = np.bincount(key, minlength=bins ** 3)
    order = np.argsort(-counts, kind="stable")[:top]
    out, nn = [], len(rgb_lin)
    for b in order:
        if counts[b] == 0:
            continue
        mean = rgb_lin[key == b].mean(axis=0)
        hexc = "#" + "".join("%02x" % int(round(linear_to_srgb_f(float(c)) * 255.0))
                             for c in mean)
        out.append({"hex_srgb": hexc,
                    "linear_rgb": [round(float(v), 6) for v in mean],
                    "weight": round(float(counts[b]) / nn, 6)})
    return out


