MYSTERY = (b"x.werk-future.mystery v1\n"
           b"A payload shape that does not exist yet. If you are reading this in "
           b"a reader that understands it, this fixture is older than you.\n")

CORRUPT_TARGET = "points/cc0-sphere.wkpc"


def _add_mystery(ctx):
    ctx.files["x/mystery/blob.bin"] = MYSTERY
    ctx.nodes.append({
        "node_id": "mystery", "type": "x.werk-future.mystery",
        "versions": [{"v": 1, "files": [{"path": "x/mystery/blob.bin",
                                         "sha256": sha256(MYSTERY),
                                         "size": len(MYSTERY)}],
                      "note": "A node type from a version of the format this "
                              "reader has never heard of. It must be listed, "
                              "hash-verified and skipped WITH A REPORT, never a "
                              "failure (law 12).",
                      "producer": {"tool": "fixtures/build_gsplat_cc0.py",
                                   "version": "1"},
                      "epistemic": "authored", "created": CREATED}],
        "active": 1, "edges": []})


def build(scratch_dir):
    # clean
    ctx, lic, summary, stats, pc_stats = populate(scratch_dir)
    _m, _s, entries = PKG.assemble(ctx, lic, summary)
    clean_blob = write_zip(entries)

    # damaged: rebuild fresh, add the mystery node, re-sign, then flip one byte
    dctx, dlic, dsummary, _st, _pc = populate(scratch_dir)
    _add_mystery(dctx)
    _dm, _ds, dentries = PKG.assemble(dctx, dlic, dsummary)
    off = 1000 if len(dctx.files[CORRUPT_TARGET]) > 1001 else 5
    dentries = [(p, (d[:off] + bytes([d[off] ^ 0xFF]) + d[off + 1:])
                 if p == CORRUPT_TARGET else d) for p, d in dentries]
    dmg_blob = write_zip(dentries)

    return clean_blob, dmg_blob, len(ctx.nodes), stats, pc_stats, CORRUPT_TARGET, off


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", default=HERE)
    ap.add_argument("--scratch", default=os.path.join(ROOT, "data", "cc0-gsplat"))
    ap.add_argument("--check-determinism", action="store_true")
    args = ap.parse_args(argv)

    clean_blob, dmg_blob, nnodes, stats, pc_stats, target, off = build(args.scratch)

    clean_path = os.path.join(args.out, "gsplat-cc0-v1.werk")
    dmg_path = os.path.join(args.out, "gsplat-cc0-v1-damaged.werk")
    with open(clean_path, "wb") as fh:
        fh.write(clean_blob)
    with open(dmg_path, "wb") as fh:
        fh.write(dmg_blob)

    print("splat %d Gaussians, sh_degree %d, %d bytes WKGS; point cloud %d points"
          % (stats["count"], stats["sh_degree"], stats["bytes"], pc_stats["count"]))
    print("bounds min %s max %s (metres)"
          % ([round(v, 4) for v in stats["bounds_min_m"]],
             [round(v, 4) for v in stats["bounds_max_m"]]))
    print("wrote %s" % clean_path)
    print("  %d bytes, sha256 %s" % (len(clean_blob), sha256(clean_blob)))
    print("  %d nodes" % nnodes)
    print("wrote %s" % dmg_path)
    print("  %d bytes, sha256 %s" % (len(dmg_blob), sha256(dmg_blob)))
    print("  damage: 1 flipped byte in %s (offset %d), plus x.werk-future.mystery"
          % (target, off))

    if args.check_determinism:
        c2, d2, _n, _s, _p, _t, _o = build(args.scratch)
        ok = (sha256(c2) == sha256(clean_blob) and sha256(d2) == sha256(dmg_blob))
        print("determinism: %s (two builds, whole-file sha256 %s)"
              % ("PASS" if ok else "FAIL", "identical" if ok else "DIFFER"))
        if not ok:
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
