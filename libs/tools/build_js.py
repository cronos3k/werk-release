#!/usr/bin/env python3
"""build_js.py -- assemble the two JavaScript builds from ONE core source.

    python tools/build_js.py

    js/dist/werk.js    Uint8Array adapter + Node file IO (when `fs` exists) +
                       core + bundle. CommonJS (`require("./werk.js")`), a
                       global `werk` otherwise. Node 18+, Adobe UXP, browsers.
    js/dist/werk.jsx   binary-string adapter + ExtendScript File IO (or Node
                       IO when run under Node, for testing) + the SAME core +
                       bundle. ES3: Adobe ExtendScript (#include "werk.jsx").

The core (js/src/core.js) is written in ES3 syntax so both builds are the
same code; only the byte adapter and the IO adapter differ.
"""

import base64
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
LIBS = os.path.dirname(HERE)
SRC = os.path.join(LIBS, "js", "src")
DIST = os.path.join(LIBS, "js", "dist")


def rd(name):
    with open(os.path.join(SRC, name), encoding="utf-8") as fh:
        return fh.read()


def js_string(s):
    # A JSON string literal is a valid ES3 string literal; escape everything
    # outside ASCII so the build file itself is ASCII (ExtendScript reads
    # #include files in the system code page unless told otherwise).
    return json.dumps(s, ensure_ascii=True)


def bundle_js():
    bdir = os.path.join(LIBS, "bundle")
    text = open(os.path.join(bdir, "bundle.json"), encoding="utf-8").read()
    info = json.loads(text)
    out = ["var WERK_BUNDLE_JSON = %s;" % js_string(text), "var WERK_BUNDLE_FILES = {};"]
    for f in info["files"]:
        data = open(os.path.join(bdir, *f["path"].split("/")), "rb").read()
        out.append("WERK_BUNDLE_FILES[%s] = %s;" % (json.dumps(f["path"]),
                                                     json.dumps(base64.b64encode(data).decode("ascii"))))
    return "\n".join(out) + "\n"


EXPORTS = """
var api = {
  version: LIB_VERSION, B: B, WerkError: WerkError, WFloat: WFloat, WInt: WInt,
  Package: Package, Node: Node, PackageWriter: PackageWriter, file: file,
  open: function (path, io) { io = io || IO; if (!io) { throw new WerkError("no file IO here: use werk.openBytes(bytes)"); } return new Package(openContainer(io, path), path); },
  openBytes: function (bytes, name) { return new Package(new ZipContainer(bytes), name || "<bytes>"); },
  writeImagePackage: function (out, png, opts) { var w = buildImagePackage(png, opts); w.write(out, (opts && opts.form) || null, opts && opts.io); return w; },
  writeMeshPackage: function (out, glb, opts) { var w = buildMeshPackage(glb, opts); w.write(out, (opts && opts.form) || null, opts && opts.io); return w; },
  buildImagePackage: buildImagePackage, buildMeshPackage: buildMeshPackage,
  appendVersion: appendVersion, signPackage: signPackage, payloadPath: payloadPathOf,
  jsonParse: jsonParse, jsonParseBytes: jsonParseBytes, jsonPretty: jsonPretty, jsonCanonical: jsonCanonical, pyFloat: pyFloat,
  sha256Hex: sha256Hex, crc32: crc32, specSha256Of: specSha256Of, inputHashOf: inputHashOf,
  ed25519Sign: ed25519Sign, ed25519Verify: ed25519Verify, ed25519PublicKey: ed25519PublicKey,
  verifyChain: verifyChain, readEnvelope: readEnvelope, inflateRaw: inflateRaw,
  utf8Encode: utf8Encode, utf8Decode: utf8Decode, fromHex: fromHex, toHex: toHex,
  physicalOrder: physicalOrder, pngInfo: pngInfo, glbInfo: glbInfo, defaultBundle: defaultBundle,
  cli: cli, io: function () { return IO; }, setIO: function (x) { IO = x; }
};
"""

HEAD_NODE = """/* werk %(v)s -- read and write werk packages. GENERATED by libs/tools/build_js.py
 * from js/src/{adapter-u8,io-node,core}.js and the vendored bundle; do not edit.
 * No dependencies. Node 18+ (file IO through fs), Adobe UXP and browsers
 * (werk.openBytes / writer.toBytes; pass your own io for files). */
(function (root) {
"use strict";
"""

TAIL_NODE = """
var IO = null;
try { if (typeof process !== "undefined" && process.versions && process.versions.node) { IO = makeNodeIO(B); } } catch (e) { IO = null; }
%(exports)s
if (typeof module !== "undefined" && module.exports) { module.exports = api; } else { root.werk = api; }
})(this);
"""

HEAD_JSX = """/* werk %(v)s -- ES3 build for Adobe ExtendScript. GENERATED by
 * libs/tools/build_js.py from js/src/{adapter-str,io-jsx,io-node,core}.js and
 * the vendored bundle; do not edit. Usage in a host script:
 *     #include "werk.jsx"
 *     var pkg = werk.open("C:/path/thing.werk"); pkg.verdict();
 * Bytes are binary strings (one char per byte). Same core as dist/werk.js. */
var werk = (function () {
"""

TAIL_JSX = """
var IO = null;
if (typeof File !== "undefined" && typeof Folder !== "undefined" && typeof $ !== "undefined") { IO = makeJsxIO(B); }
else { try { if (typeof process !== "undefined" && process.versions && process.versions.node) { IO = makeNodeIO(B); } } catch (e) { IO = null; } }
%(exports)s
return api;
})();
if (typeof module !== "undefined" && module.exports) { module.exports = werk; }
"""


def main():
    os.makedirs(DIST, exist_ok=True)
    v = json.load(open(os.path.join(LIBS, "bundle", "bundle.json"), encoding="utf-8"))["lib_version"]
    core, bundle = rd("core.js"), bundle_js()
    node = (HEAD_NODE % {"v": v} + rd("adapter-u8.js") + rd("io-node.js") + core + bundle
            + TAIL_NODE % {"exports": EXPORTS})
    jsx = (HEAD_JSX % {"v": v} + rd("adapter-str.js") + rd("io-jsx.js")
           + "/*@node-only-begin*/" + chr(10) + rd("io-node.js") + "/*@node-only-end*/" + chr(10) + core
           + bundle + TAIL_JSX % {"exports": EXPORTS})
    for name, text in (("werk.js", node), ("werk.jsx", jsx)):
        with open(os.path.join(DIST, name), "w", encoding="ascii", newline="\n") as fh:
            fh.write(text)
        print("wrote js/dist/%s (%d bytes)" % (name, len(text)))


if __name__ == "__main__":
    main()
