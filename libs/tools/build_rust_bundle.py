#!/usr/bin/env python3
"""build_rust_bundle.py -- give werkc the same bundle as the Python and JS writers.

    python tools/build_rust_bundle.py [<repo root of the werkc worktree>]

Copies bundle/bundle.json to core/src/bin/werkc_rel/bundle.json and writes
core/src/bin/werkc_rel/bundle_files.rs, which `include_bytes!`s every listed
file FROM THE REPOSITORY'S OWN spec/ AND loaders/ -- the files the crate
already ships. werkc checks each one against bundle.json's sha256 before it
writes a byte, so a repository whose spec/ drifted from the bundle refuses
loudly instead of writing a package whose spec_sha256 nobody else reproduces.
"""

import json
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
LIBS = os.path.dirname(HERE)


def main():
    repo = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(LIBS)
    rel = os.path.join(repo, "core", "src", "bin", "werkc_rel")
    os.makedirs(rel, exist_ok=True)
    shutil.copyfile(os.path.join(LIBS, "bundle", "bundle.json"), os.path.join(rel, "bundle.json"))
    info = json.load(open(os.path.join(LIBS, "bundle", "bundle.json"), encoding="utf-8"))
    lines = ["// GENERATED by libs/tools/build_rust_bundle.py -- do not edit.",
             "// Every file bundle.json lists, taken from this repository's own tree.",
             "pub const FILES: &[(&str, &[u8])] = &["]
    for f in info["files"]:
        lines.append('    ("%s", include_bytes!("../../../../%s")),' % (f["path"], f["path"]))
    lines.append("];")
    lines.append('pub const BUNDLE_JSON: &str = include_str!("bundle.json");')
    with open(os.path.join(rel, "bundle_files.rs"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote %s (%d files)" % (os.path.join(rel, "bundle_files.rs"), len(info["files"])))


if __name__ == "__main__":
    main()
