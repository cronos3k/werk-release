#!/usr/bin/env python3
"""build_single.py -- python/werk_single.py = python/werk/_core.py + the bundle.

    python tools/build_single.py

The single file is what a host vendors when it can carry one .py and nothing
else: the library code verbatim, then the bundle (bundle.json, spec/, loaders/)
as one zlib-compressed, base64-armoured blob, then a `__main__` stanza so
`python werk_single.py verify x.werk` is the CLI. The blob is decoded once, at
import, and every file is checked against bundle.json's sha256 when it is used.
"""

import base64
import json
import os
import struct
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
LIBS = os.path.dirname(HERE)


def main():
    core = open(os.path.join(LIBS, "python", "werk", "_core.py"), encoding="utf-8").read()
    bdir = os.path.join(LIBS, "bundle")
    info = json.load(open(os.path.join(bdir, "bundle.json"), encoding="utf-8"))
    names = ["bundle.json"] + [f["path"] for f in info["files"]]
    blob = b""
    for n in names:
        data = open(os.path.join(bdir, *n.split("/")), "rb").read()
        nb = n.encode("utf-8")
        blob += struct.pack("<HI", len(nb), len(data)) + nb + data
    packed = base64.b64encode(zlib.compress(blob, 9)).decode("ascii")
    lines = [packed[i:i + 100] for i in range(0, len(packed), 100)]
    tail = [
        "",
        "",
        "# ---------------------------------------------------------------------------",
        "# The embedded bundle (generated by libs/tools/build_single.py; do not edit):",
        "# bundle.json, spec/ and loaders/ as one zlib stream, base64-armoured.",
        "# ---------------------------------------------------------------------------",
        "",
        "_BUNDLE_B64 = (",
    ] + ['    "%s"' % ln for ln in lines] + [
        ")",
        "",
        "",
        "def _unpack_bundle():",
        "    raw = zlib.decompress(binascii.a2b_base64(_BUNDLE_B64))",
        "    out, o = {}, 0",
        "    while o < len(raw):",
        "        nl, dl = struct.unpack_from('<HI', raw, o)",
        "        o += 6",
        "        name = raw[o:o + nl].decode('utf-8')",
        "        out[name] = raw[o + nl:o + nl + dl]",
        "        o += nl + dl",
        "    return out",
        "",
        "",
        "_EMBEDDED_BUNDLE = _unpack_bundle()",
        "",
        "if __name__ == '__main__':",
        "    sys.exit(main())",
        "",
    ]
    marker = "_EMBEDDED_BUNDLE = None"
    assert marker in core
    text = core.rstrip("\n") + "\n" + "\n".join(tail)
    out = os.path.join(LIBS, "python", "werk_single.py")
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s (%d bytes, %d bundle files)" % (out, len(text.encode("utf-8")), len(names) - 1))


if __name__ == "__main__":
    main()
