#!/usr/bin/env python3
"""make_bundle.py -- build the vendored `spec/` + `loaders/` bundle every werk
writer in libs/ carries, from ONE source, so the four writers emit the same bytes.

    python tools/make_bundle.py --git <repo> --rev <commit>     (preferred: exact blob bytes)
    python tools/make_bundle.py --dir <tree containing spec/ and loaders/>

Writes, relative to libs/:

    bundle/spec/**, bundle/loaders/*   the files, byte for byte
    bundle/bundle.json                 file list (path, sha256, size, crc32),
                                       the core.spec / core.loader node records,
                                       the default texts and the profile tables
    python/werk/bundle/                a copy of bundle/ (the package is self-contained)
    python/werk_single.py              regenerated by tools/build_single.py (run separately)
    js/src/bundle-data.js              regenerated by tools/build_js.py (run separately)

Why from git blobs: a Windows checkout with autocrlf can hold text files whose
bytes are not the repository's, and a spec_sha256 computed over those bytes is
reproducible by nobody else (finding F-AC-6 of the source repository).

The default texts and tables in here are the ONLY place they exist; every
writer (Python, JavaScript, Rust) reads them from bundle.json, which is what
keeps their output byte-identical.
"""

import argparse
