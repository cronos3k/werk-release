def git_files(repo, rev):
    out = subprocess.check_output(
        ["git", "-C", repo, "ls-tree", "-r", "-z", "--name-only", rev, "--", "spec", "loaders"])
    names = [n.decode("utf-8") for n in out.split(b"\0") if n]
    files = {}
    for n in names:
        files[n] = subprocess.check_output(["git", "-C", repo, "cat-file", "blob", "%s:%s" % (rev, n)])
    full = subprocess.check_output(["git", "-C", repo, "rev-parse", rev]).decode().strip()
    return files, full


def dir_files(root):
    files = {}
    for top in ("spec", "loaders"):
        for dp, _dn, fn in os.walk(os.path.join(root, top)):
            for f in fn:
                if f.endswith(".pyc"):
                    continue
                full = os.path.join(dp, f)
                rel = os.path.relpath(full, root).replace(os.sep, "/")
                with open(full, "rb") as fh:
                    files[rel] = fh.read()
    return files, None


def capabilities(data):
    head = b"\n".join(data.split(b"\n")[:200])
    at = head.find(MARK)
    if at < 0:
        raise SystemExit("loader states no capabilities")
    line = head[at + len(MARK):].split(b"\n", 1)[0]
    return [c.decode("ascii") for c in line.replace(b"*/", b" ").split()]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--git")
    ap.add_argument("--rev", default="HEAD")
    ap.add_argument("--dir")
    a = ap.parse_args()
    if a.git:
        files, rev = git_files(a.git, a.rev)
    elif a.dir:
        files, rev = dir_files(a.dir)
    else:
        ap.error("--git or --dir")
    for p, d in files.items():
        if b"\r" in d and p.rsplit(".", 1)[-1] in ("md", "json", "txt", "py", "rs", "c", "h"):
            raise SystemExit("REFUSING: %s contains CR bytes; not the repository's bytes" % p)
    for _nid, fname, _l, _t, _b in LOADERS:
        if "loaders/" + fname not in files:
            raise SystemExit("source has no loaders/%s" % fname)

    paths = sorted(files, key=lambda p: p.encode("utf-8"))
    records = []
    for p in paths:
        d = files[p]
        records.append(OrderedDict([("path", p), ("sha256", hashlib.sha256(d).hexdigest()),
                                    ("size", len(d)), ("crc32", zlib.crc32(d) & 0xFFFFFFFF)]))
    loaders = []
    for nid, fname, lang, tool, build in LOADERS:
        data = files["loaders/" + fname]
        meta = OrderedDict([("language", lang), ("form", "source"),
                            ("entrypoint", "loaders/" + fname), ("toolchain", tool),
                            ("dependencies", [])])
        meta["capabilities"] = capabilities(data)
        if build:
            meta["build_command"] = build
        loaders.append(OrderedDict([("node_id", nid), ("path", "loaders/" + fname), ("meta", meta)]))

    schemas = OrderedDict()
    for p in paths:
        if p.startswith("spec/schemas/core.") and p.endswith(".schema.json"):
            schemas[p[len("spec/schemas/"):-len(".schema.json")]] = p
    bundle = OrderedDict([
        ("bundle_version", 1),
        ("lib_version", LIB_VERSION),
        ("source_rev", rev),
        ("files", records),
        ("loaders", loaders),
        ("texts", TEXTS),
        ("head_order", HEAD_ORDER),
        ("profiles", PROFILES),
        ("base_conventions", CONV_BASE),
        ("schemas_by_type", schemas),
        ("layouts_by_type", OrderedDict((k, v) for k, v in LAYOUTS.items() if v in files)),
    ])

    out = os.path.join(LIBS, "bundle")
    if os.path.isdir(out):
        shutil.rmtree(out)
    for p in paths:
        full = os.path.join(out, *p.split("/"))
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "wb") as fh:
            fh.write(files[p])
    text = json.dumps(bundle, indent=1, ensure_ascii=False) + "\n"
    with open(os.path.join(out, "bundle.json"), "wb") as fh:
        fh.write(text.encode("utf-8"))
    pyb = os.path.join(LIBS, "python", "werk", "bundle")
    if os.path.isdir(pyb):
        shutil.rmtree(pyb)
    shutil.copytree(out, pyb)
    print("bundle: %d files, %d bytes, rev %s" % (len(paths), sum(len(v) for v in files.values()), rev))


if __name__ == "__main__":
    main()
