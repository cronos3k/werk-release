#!/usr/bin/env python3
"""p_texture.py — the texture cook: core.tex nodes plus mip chains.

Every image the source GLB carried becomes a core.tex node with the meta the
profile's node table requires (color_space, usage, size, bit_depth), and a mip
chain generated by 2x2 box reduction.

The mips are the part that has to be right. An sRGB-encoded base colour map
averaged in its encoded values is darker than the surface it stands for; the
error is small per level and compounds down the chain. So sRGB maps are decoded
to linear, averaged, and re-encoded, and linear maps (normal, metallic-
roughness, occlusion) are averaged where they already live. Which of the two
happened is written into the node's meta, because a consumer that does its own
mip generation needs to know whether these were made the same way.

Normal maps get a third treatment: the vectors are decoded to [-1,1],
renormalised after averaging and re-encoded, because the mean of two unit
vectors is not a unit vector and a shortened normal reads as a shinier surface.
"""

import io

import numpy as np

from .common import png_bytes, png_info, kebab

USAGE = {
    "base_color_texture": ("base-color", "srgb"),
    "metallic_roughness_texture": ("metallic-roughness", "linear"),
    "normal_texture": ("normal", "linear"),
    "occlusion_texture": ("occlusion", "linear"),
    "emissive_texture": ("emissive", "srgb"),
}


def _decode(blob):
    from PIL import Image
    im = Image.open(io.BytesIO(blob))
    if im.mode not in ("RGB", "RGBA", "L"):
        im = im.convert("RGBA" if "A" in im.mode else "RGB")
    return np.asarray(im), im.mode


def _reduce(a, color_space, usage):
    h, w = a.shape[:2]
    hh, ww = max(1, h // 2), max(1, w // 2)
    src = a[:hh * 2, :ww * 2].astype(np.float64)
    if src.ndim == 2:
        src = src[:, :, None]
    q = src.reshape(hh, 2, ww, 2, src.shape[2])
    if usage == "normal":
        v = q[..., :3] / 255.0 * 2.0 - 1.0
        m = v.mean(axis=(1, 3))
        m = m / np.maximum(np.linalg.norm(m, axis=-1, keepdims=True), 1e-12)
        out = np.zeros((hh, ww, src.shape[2]))
        out[..., :3] = (m * 0.5 + 0.5) * 255.0
        if src.shape[2] > 3:
            out[..., 3:] = q[..., 3:].mean(axis=(1, 3))
    elif color_space == "srgb":
        s = q / 255.0
        lin = np.where(s <= 0.04045, s / 12.92, ((s + 0.055) / 1.055) ** 2.4)
        if src.shape[2] == 4:
            lin[..., 3] = s[..., 3]            # alpha is never gamma-encoded
        m = lin.mean(axis=(1, 3))
        enc = np.where(m <= 0.0031308, m * 12.92,
                       1.055 * np.maximum(m, 0.0) ** (1 / 2.4) - 0.055)
        if src.shape[2] == 4:
            enc[..., 3] = m[..., 3]
        out = enc * 255.0
    else:
        out = q.mean(axis=(1, 3))
    out = np.clip(np.round(out), 0, 255)
    return out[:, :, 0] if a.ndim == 2 else out


def run(ctx, scene, max_levels=12):
    """Returns {image_index: {"node": id, "path": p, "array": rgba float [0,1]}}"""
    # which image serves which slot, so usage and colour space are not guessed
    slot_of = {}
    for mat in scene.materials:
        for key, (usage, cs) in USAGE.items():
            t = mat.get(key)
            if t:
                slot_of.setdefault(t["image"], (usage, cs))

    made = {}
    for ii, (blob, mime) in enumerate(scene.images):
        if blob is None:
            ctx.notes.append("image %d is an external URI and was not copied" % ii)
            continue
        usage, cs = slot_of.get(ii, ("other", "srgb"))
        arr, mode = _decode(blob)
        h, w = arr.shape[:2]
        if mime == "image/png":
            out_blob, ext = blob, "png"
            info = png_info(blob)
            bit_depth = info["bit_depth"]
        else:
            mo = "RGBA" if arr.ndim == 3 and arr.shape[2] == 4 else (
                "RGB" if arr.ndim == 3 else "L")
            if mo == "L":
                arr3 = np.stack([arr] * 3, axis=-1)
                out_blob, mo = png_bytes(arr3, "RGB"), "RGB"
                arr = arr3
            else:
                out_blob = png_bytes(arr, mo)
            ext = "png"
            bit_depth = 8
        slug = kebab("tex-%02d-%s" % (ii, usage))
        base_path = "textures/%s.%s" % (slug, ext)
        files = [ctx.put(base_path, out_blob)]

        mips = []
        cur = arr
        lvl = 0
        while min(cur.shape[0], cur.shape[1]) > 1 and lvl < max_levels:
            cur = _reduce(cur, cs, usage)
            lvl += 1
            mo = "RGBA" if cur.ndim == 3 and cur.shape[2] == 4 else (
                "RGB" if cur.ndim == 3 else "L")
            if mo == "L":
                cur3 = np.stack([cur] * 3, axis=-1)
                mb = png_bytes(cur3, "RGB")
            else:
                mb = png_bytes(cur, mo)
            mp = "textures/%s.mip%02d.png" % (slug, lvl)
            files.append(ctx.put(mp, mb))
            mips.append({"level": lvl, "path": mp,
                         "width": int(cur.shape[1]), "height": int(cur.shape[0])})

        method = ("linear-space-box-2x2" if cs == "srgb" else "box-2x2")
        if usage == "normal":
            method = "box-2x2-renormalised"
        node_id = "tex-%02d-%s" % (ii, usage)
        meta = {"color_space": cs, "usage": usage,
                "width": int(w), "height": int(h), "bit_depth": bit_depth,
                "channels": int(arr.shape[2]) if arr.ndim == 3 else 1,
                "mip_levels": len(mips), "mip_filter": method,
                "mips": mips, "source_mime": mime}
        if usage == "normal":
            # glTF 2.0 fixes tangent-space normal maps as +Y up (OpenGL), so
            # this is the source's own declaration restated, not a guess.
            meta["normal_convention"] = "opengl-y-up"
        ctx.node(node_id, "core.tex",
                 ctx.version(files,
                             "Source image %d, %dx%d, usage '%s'. %d mip levels, "
                             "generated by %s. The base level is the source "
                             "image%s." % (ii, w, h, usage, len(mips), method,
                                           " byte for byte" if mime == "image/png"
                                           else " re-encoded from %s to PNG" % mime),
                             "measured", inputs=["geometry/source.glb"],
                             params={"image_index": ii, "mip_filter": method}),
                 edges=[{"to": "geom-source", "kind": "enhances",
                         "role": "texture-of"}],
                 meta=meta)
        made[ii] = {"node": node_id, "path": base_path, "usage": usage,
                    "color_space": cs, "array": arr, "mips": len(mips)}
    if not made:
        raise ValueError("the GLB carries no embedded images")
    return made
