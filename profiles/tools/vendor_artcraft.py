#!/usr/bin/env python3
"""vendor_artcraft.py -- copy the six ArtCraft profile definitions into profiles/<name>/.

Provenance tool (run once by W19, 2026-11-20; kept so the copy can be re-made and checked).
Reads the ArtCraft sample packages (read-only) and writes, per profile:

  profiles/<name>/spec/...        every spec/ file the app's samples carry that the release
                                  spec/ does not have (the profile narrative, CRAFT-BASE.md,
                                  NOT-CARRIED.md, conventions map, schemas, layouts, examples);
                                  spec/formats/ is excluded (shared, see profiles/_formats/)
  profiles/<name>/HOW-TO-READ.md  the app's package-root reading guide (template)
  profiles/_formats/              the format definitions the fixtures use, from
                                  werk-integration/formats (definition, reference tool source,
                                  and its tool.json as the ArtCraft writers emit it)
  profiles/VENDORED.json          source path and sha256 of every copied file

Files whose path the release spec/ already has (SPEC.md, MINI-SPECS.md, README.md,
ENVELOPE.layout.txt, core.revisions.schema.json, the signature examples) are NOT copied: a
package written by the release library carries the release copies of those.
Alignment edits are not made here; profiles/tools/align_profiles.py makes them and records them.

usage: vendor_artcraft.py --samples <artcraft>/werk-integration/samples
                          --formats <artcraft>/werk-integration/formats --artcraft <artcraft> --repo <repo>
                          [--generated <dir of schemas from effectcraft-werk schema::of>]
"""
import argparse, hashlib, json, os, shutil, zipfile

APPS = [("photocraft", "raster-layers", "maximal-dir.werk"),
        ("vectorcraft", "vector-art", "every-field-signed-directory"),
        ("effectcraft", "motion-comp", "intro-folder.werk"),
        ("wordcraft", "rich-document", "report-directory.werk"),
        ("gridcraft", "spreadsheet", "every-field-signed-directory"),
        ("deckcraft", "presentation", "every-field-signed-directory")]
FORMATS = {"zlib-deflate": ["inflate.py"], "zip": ["zip_dump.py"]}
TOOL_JSON_FROM = {"zlib-deflate": "photocraft/simple.werk", "zip": "photocraft/maximal.werk"}


# Files the narrative of a profile names that its sample packages do not carry (a sample carries
# only what its own nodes use). From the app repository at the commit the samples were written
# from ("git"), or generated by the app's own schema code ("generated": the bytes cannot be
# re-made by this script; it checks their sha256). motion-comp/1 only.
EFFECTCRAFT = ("effectcraft", "werk-native")   # repository under --artcraft, branch
EXTRA_GIT = [("motion-comp", "spec/layouts/core.expr.baked.layout.txt", "crates/werk/spec/layouts/core.expr.baked.layout.txt"),
             ("motion-comp", "spec/layouts/x.effectcraft.media.layout.txt", "crates/werk/spec/layouts/x.effectcraft.media.layout.txt")]
EXTRA_GENERATED = {
    "how": "effectcraft-werk `schema::of(type)` (werk-native ea503b9), run by W19 in a mirror build on the release "
           "core (example w19_schemas); the seven schemas the sample also carries came out byte-identical to the "
           "sample's copies",
    "files": {("motion-comp", "spec/schemas/core.motion.render-queue.schema.json"):
              None,
              ("motion-comp", "spec/schemas/core.expr.language.schema.json"): None,
              ("motion-comp", "spec/schemas/core.expr.baked-values.schema.json"): None,
              ("motion-comp", "spec/schemas/x.effectcraft.plugin-state.schema.json"): None}}


def sha(b):
    return hashlib.sha256(b).hexdigest()


def pkg_files(p):
    out = {}
    if os.path.isdir(p):
        for dp, _dn, fn in os.walk(p):
            for f in fn:
                full = os.path.join(dp, f)
                out[os.path.relpath(full, p).replace("\\", "/")] = open(full, "rb").read()
    else:
        z = zipfile.ZipFile(p)
        for n in z.namelist():
            if not n.endswith("/"):
                out[n] = z.read(n)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--samples", required=True); ap.add_argument("--formats", required=True)
    ap.add_argument("--repo", required=True)
    ap.add_argument("--artcraft", required=True, help="the folder holding the ArtCraft app repositories")
    ap.add_argument("--generated", help="directory holding the schemas EXTRA_GENERATED names")
    a = ap.parse_args()
    prof_root = os.path.join(a.repo, "profiles")
    record = {"note": "Copied byte for byte from the ArtCraft sample packages (werk-native branches, "
                      "2026-10-13..16). Alignment edits: profiles/ALIGNMENT.json.", "profiles": {}, "formats": {}}
    for app, name, primary in APPS:
        appdir = os.path.join(a.samples, app)
        union = {}
        src_of = {}
        for e in sorted(os.listdir(appdir)):
            p = os.path.join(appdir, e)
            if not (e.endswith(".werk") or os.path.isdir(p)):
                continue
            fs = pkg_files(p)
            if "MANIFEST.json" not in fs:
                continue
            for k, v in fs.items():
                if not k.startswith("spec/") or k.startswith("spec/formats/"):
                    continue
                if "@" in os.path.basename(k):
                    continue
                if os.path.exists(os.path.join(a.repo, k)):
                    continue
                if k in union and union[k] != v:
                    raise SystemExit("conflict %s %s" % (app, k))
                union[k] = v
                src_of.setdefault(k, "%s/%s" % (app, e))
        dst = os.path.join(prof_root, name)
        if os.path.isdir(os.path.join(dst, "spec")):
            shutil.rmtree(os.path.join(dst, "spec"))
        files = {}
        for k in sorted(union):
            out = os.path.join(dst, k)
            os.makedirs(os.path.dirname(out), exist_ok=True)
            open(out, "wb").write(union[k])
            files[k] = {"sha256": sha(union[k]), "size": len(union[k]), "from": src_of[k]}
        for prof, dst_rel, src_rel in EXTRA_GIT:
            if prof != name:
                continue
            import subprocess
            b = subprocess.run(["git", "-C", os.path.join(a.artcraft, EFFECTCRAFT[0]), "show", "%s:%s" % (EFFECTCRAFT[1], src_rel)],
                               stdout=subprocess.PIPE, check=True).stdout
            out = os.path.join(dst, dst_rel)
            os.makedirs(os.path.dirname(out), exist_ok=True)
            open(out, "wb").write(b)
            files[dst_rel] = {"sha256": sha(b), "size": len(b), "from": "git <artcraft>/%s %s:%s" % (EFFECTCRAFT[0], EFFECTCRAFT[1], src_rel)}
        for (prof, rel), want in EXTRA_GENERATED["files"].items():
            if prof != name:
                continue
            src = os.path.join(a.generated, os.path.basename(rel)) if a.generated else None
            if src and os.path.exists(src):
                b = open(src, "rb").read()
                out = os.path.join(dst, rel)
                os.makedirs(os.path.dirname(out), exist_ok=True)
                open(out, "wb").write(b)
                files[rel] = {"sha256": sha(b), "size": len(b), "from": "generated: " + EXTRA_GENERATED["how"]}
            else:
                print("NOTE %s %s: generated file not given (--generated), not copied" % (prof, rel))
        htr = pkg_files(os.path.join(appdir, primary))["HOW-TO-READ.md"]
        open(os.path.join(dst, "HOW-TO-READ.md"), "wb").write(htr)
        files["HOW-TO-READ.md"] = {"sha256": sha(htr), "size": len(htr), "from": "%s/%s" % (app, primary)}
        record["profiles"][name] = {"app": app, "files": files}
    fdst = os.path.join(prof_root, "_formats")
    for fid, tools in FORMATS.items():
        d = open(os.path.join(a.formats, fid + ".md"), "rb").read()
        os.makedirs(os.path.join(fdst, "spec", "formats"), exist_ok=True)
        open(os.path.join(fdst, "spec", "formats", fid + ".md"), "wb").write(d)
        ent = {"definition": {"sha256": sha(d), "size": len(d), "from": "formats/%s.md" % fid}, "tools": {}}
        tdir = os.path.join(fdst, "tools", "format-%s-reference" % fid)
        os.makedirs(tdir, exist_ok=True)
        for t in tools:
            b = open(os.path.join(a.formats, "ref", t), "rb").read()
            open(os.path.join(tdir, t), "wb").write(b)
            ent["tools"][t] = {"sha256": sha(b), "size": len(b), "from": "formats/ref/%s" % t}
        # the core.tool descriptor as the ArtCraft writers emit it (TOOL_JSON_FROM)
        tj = pkg_files(os.path.join(a.samples, TOOL_JSON_FROM[fid]))["tools/format-%s-reference/tool.json" % fid]
        open(os.path.join(tdir, "tool.json"), "wb").write(tj)
        ent["tools"]["tool.json"] = {"sha256": sha(tj), "size": len(tj), "from": TOOL_JSON_FROM[fid]}
        record["formats"][fid] = ent
    with open(os.path.join(prof_root, "VENDORED.json"), "w", encoding="utf-8", newline="\n") as fh:
        json.dump(record, fh, indent=1, sort_keys=True, ensure_ascii=False)
        fh.write("\n")
    for name in record["profiles"]:
        print(name, len(record["profiles"][name]["files"]), "files")


if __name__ == "__main__":
    main()
