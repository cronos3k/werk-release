#!/usr/bin/env python3
"""write_pins.py -- profiles/PINS.md from profiles/fixtures/fixtures.json and the fixtures.

    python profiles/tools/write_pins.py [--results profiles/results]

The table of the six fixtures (bytes, sha256, MANIFEST.json sha256, the package's spec_sha256,
nodes, files), the bytes the fixtures share by content, and the release spec digest measured
over spec/ of the working tree (tools/spec_sha256.py), which must stay 55882f4b...
"""
import hashlib
import json
import os
import subprocess
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
PROFILES = os.path.dirname(HERE)
REPO = os.path.dirname(PROFILES)
RELEASE_SPEC = "55882f4b05e7fee1c1113662499dc5c62297020c23aa5d271c42ccb8791d40b3"


def sha(b):
    return hashlib.sha256(b).hexdigest()


def main():
    fx = json.load(open(os.path.join(PROFILES, "fixtures", "fixtures.json"), encoding="utf-8"))
    rows = fx["fixtures"]
    z = {n: zipfile.ZipFile(os.path.join(PROFILES, "fixtures", r["file"])) for n, r in rows.items()}
    vec_bytes = open(os.path.join(PROFILES, "fixtures", rows["vector-art"]["file"]), "rb").read()
    shared = [
        ("raster-layers composite preview PNG", "raster-layers-v1.werk", "preview/composite.png",
         sha(z["raster-layers"].read("preview/composite.png"))),
        ("the same PNG as the report's picture", "rich-document-v1.werk", "media/harbour-at-dusk.png",
         sha(z["rich-document"].read("media/harbour-at-dusk.png"))),
        ("the same PNG as the deck's photograph (media 11)", "presentation-v1.werk",
         "deck/media/media-11/harbour-at-dusk.png", sha(z["presentation"].read("deck/media/media-11/harbour-at-dusk.png"))),
        ("the vector-art package itself", "vector-art-v1.werk", "(the file)", sha(vec_bytes)),
        ("the same package embedded in the deck (media 10)", "presentation-v1.werk",
         "deck/media/media-10/harbour-lights-logo.werk",
         sha(z["presentation"].read("deck/media/media-10/harbour-lights-logo.werk"))),
        ("vector-art preview PNG", "vector-art-v1.werk", "preview/artboard.png",
         sha(z["vector-art"].read("preview/artboard.png"))),
        ("the same PNG as the logo's rendition in the deck", "presentation-v1.werk",
         "deck/media/media-10/rendition.png", sha(z["presentation"].read("deck/media/media-10/rendition.png"))),
    ]
    spec_now = subprocess.run([sys.executable, os.path.join(REPO, "tools", "spec_sha256.py"), os.path.join(REPO, "spec")],
                              stdout=subprocess.PIPE).stdout.decode().split()[0]
    L = ["# Profile fixture pins", "",
         "**Generated by `profiles/tools/write_pins.py`. Do not hand-edit.** The release fixture rows of",
         "`RELEASE-PINS.md` are unchanged; these six are separate.", "",
         "Release spec digest over this tree's `spec/` (`tools/spec_sha256.py spec`): `%s` — %s." % (
             spec_now, "unchanged" if spec_now == RELEASE_SPEC else "**CHANGED, expected %s**" % RELEASE_SPEC),
         "Each package's own `spec_sha256` covers the release `spec/` plus the profile's definition files it",
         "carries, so it differs from the release digest by exactly those files (SPEC §2.2).", "",
         "| fixture | profile | bytes | sha256 | MANIFEST.json sha256 | package spec_sha256 | nodes | files |",
         "|---|---|---:|---|---|---|---:|---:|"]
    for n in ["raster-layers", "vector-art", "motion-comp", "rich-document", "spreadsheet", "presentation"]:
        r = rows[n]
        L.append("| `profiles/fixtures/%s` | `%s` | %s | `%s` | `%s` | `%s` | %d | %d |" % (
            r["file"], r["profile"], format(r["bytes"], ",").replace(",", " "), r["sha256"], r["manifest_sha256"],
            r["spec_sha256"], r["nodes"], r["files"]))
    L += ["", fx["note"], "", "## Bytes shared by content", "",
          "| what | package | path | sha256 |", "|---|---|---|---|"]
    for what, pkg, path, h in shared:
        L.append("| %s | `%s` | `%s` | `%s` |" % (what, pkg, path, h))
    ok = shared[0][3] == shared[1][3] == shared[2][3] and shared[3][3] == shared[4][3] and shared[5][3] == shared[6][3]
    L += ["", "Equal where the table says so: %s." % ("yes" if ok else "**NO**"), "",
          "## What was run on them", "",
          "See `profiles/results/` (`RESULTS.md` there: commands, tool versions, exact outcomes).", ""]
    open(os.path.join(PROFILES, "PINS.md"), "w", encoding="utf-8", newline="\n").write("\n".join(L))
    print("\n".join(L))
    return 0 if ok and spec_now == RELEASE_SPEC else 1


if __name__ == "__main__":
    sys.exit(main())
