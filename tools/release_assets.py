#!/usr/bin/env python3
"""Write RELEASE-ASSETS.md from the files this repository keeps out of git,
and optionally copy them into an upload directory with the same layout.

    python tools/release_assets.py [--copy-to DIR] [--check]

The set of files is ASSETS below (repository-relative paths, each also listed
in .gitignore). Every row records the size and sha256 measured now; the URL
column carries the placeholder {RELEASE_BASE_URL}, filled in when the release
is published. `--check` compares the files on disk with the committed list and
exits 1 on any difference. tools/fetch_fixtures.py reads the list.
"""
import argparse
import hashlib
import os
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIST = os.path.join(ROOT, "RELEASE-ASSETS.md")

#: (path, why it is out of git)
ASSETS = [
    ("fixtures/crate-v1.werk", "golden fixture, > 5 MB"),
    ("fixtures/crate-v1-damaged.werk", "golden fixture (damaged twin), > 5 MB"),
    ("fixtures/ista-varun-v1.werk", "image/1 fixture, > 5 MB"),
    ("fixtures/gsplat-v1.werk", "captured Gaussian-splat fixture, > 5 MB"),
    ("fixtures/image-cc0-v1.werk", "CC0 image fixture, > 5 MB (rebuildable: fixtures/build_image_cc0.py)"),
    ("fixtures/image-cc0-v1-damaged.werk", "CC0 image fixture (damaged twin), > 5 MB"),
    ("gauntlet/roundSR/selfrun-v1.werk", "self-run gauntlet fixture, > 5 MB (frozen evidence)"),
    ("gauntlet/roundHC/pages/scanned/page-01.jpg", "hardcopy round: degraded page scan"),
    ("gauntlet/roundHC/pages/scanned/page-02.jpg", "hardcopy round: degraded page scan"),
    ("gauntlet/roundHC/pages/scanned/page-03.jpg", "hardcopy round: degraded page scan"),
]


def sha256_of(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def render(rows):
    total = sum(r[1] for r in rows)
    L = ["# Release assets — the files kept out of git",
         "",
         "**Generated by `tools/release_assets.py`. Do not hand-edit.**",
         "",
         "These files are part of the release but not of the git history: each is",
         "large, or a scan, or reproducible output. Each is pinned here by size and",
         "sha256. `python tools/fetch_fixtures.py --base-url <URL>` downloads them",
         "into place and refuses any file whose hash does not match. The URL column",
         "carries the placeholder `{RELEASE_BASE_URL}` until the release is published.",
         "",
         "| path | bytes | sha256 | url | why out of git |",
         "|---|---:|---|---|---|"]
    for rel, size, sha, why in rows:
        L.append("| `%s` | %s | `%s` | `{RELEASE_BASE_URL}/%s` | %s |"
                 % (rel, "{:,}".format(size).replace(",", " "), sha, rel, why))
    L += ["", "%d files, %s bytes in total." % (len(rows), "{:,}".format(total).replace(",", " ")), ""]
    return "\n".join(L)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--copy-to", default="")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    rows, missing = [], []
    for rel, why in ASSETS:
        p = os.path.join(ROOT, *rel.split("/"))
        if not os.path.isfile(p):
            missing.append(rel)
            continue
        rows.append((rel, os.path.getsize(p), sha256_of(p), why))
    if missing:
        print("missing: " + ", ".join(missing))
        return 1
    text = render(rows)
    if a.check:
        cur = open(LIST, encoding="utf-8").read() if os.path.isfile(LIST) else ""
        if cur != text:
            print("RELEASE-ASSETS.md does not match the files on disk")
            return 1
        print("RELEASE-ASSETS.md matches %d files" % len(rows))
        return 0
    open(LIST, "w", encoding="utf-8", newline="\n").write(text)
    print("wrote RELEASE-ASSETS.md (%d files)" % len(rows))
    if a.copy_to:
        for rel, size, sha, _ in rows:
            dst = os.path.join(a.copy_to, *rel.split("/"))
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            if not (os.path.isfile(dst) and sha256_of(dst) == sha):
                shutil.copyfile(os.path.join(ROOT, *rel.split("/")), dst)
            print("asset %s" % rel)
    return 0


if __name__ == "__main__":
    sys.exit(main())
